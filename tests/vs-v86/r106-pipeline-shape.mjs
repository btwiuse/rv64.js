#!/usr/bin/env node

// Prove R106's indivisible candidate shape from the compiled Wasm and from an
// exact subtraction back to R105.  No performance observations are consumed.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const [controlPath, candidatePath, r105SourceArchive, r064Path, outputPath] =
  process.argv.slice(2);
if (!controlPath || !candidatePath || !r105SourceArchive || !r064Path || !outputPath) {
  throw new Error(
    "usage: r106-pipeline-shape.mjs CONTROL CANDIDATE R105-SOURCE.tgz R064.wasm OUTPUT.json",
  );
}

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const EXPECTED = {
  control: "d9f686a9ce4f54734f310cf5789f900af0c9b7067539e0251c429f376dd3df6d",
  candidate: "6571795ef19c275aa8f9ae3831c9da3eae74aa7e9ea90b550ca664b0cc165165",
  r064: "dfc9026b165c63cce40dce031a8fb70b7fab5d9e5a98531294a0f8c8b34ff053",
  r105Core: "4f5fae219b2b4af676191d7561908cd0ca688bd33f1be01ac2152b6f32129694",
  r105WasmSource: "f6888d21ff82f2690bacc81e205fe4d6f37ff344c106b289b7caf2288a49d790",
};
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

function command(name, args, options = {}) {
  const child = spawnSync(name, args, {
    encoding: options.encoding ?? "utf8",
    maxBuffer: 192 << 20,
  });
  if (child.status !== 0) {
    throw new Error(child.stderr || child.stdout || `${name} failed`);
  }
  return child.stdout;
}

function uleb(bytes, cursor) {
  let value = 0;
  let shift = 0;
  while (true) {
    const byte = bytes[cursor.offset++];
    value += (byte & 0x7f) * 2 ** shift;
    if (!(byte & 0x80)) return value;
    shift += 7;
  }
}

function codeSectionBytes(bytes) {
  const cursor = { offset: 8 };
  while (cursor.offset < bytes.length) {
    const id = bytes[cursor.offset++];
    const size = uleb(bytes, cursor);
    if (id === 10) return size;
    cursor.offset += size;
  }
  throw new Error("Wasm has no CODE section");
}

function functionBodies(disassembly) {
  const headers = [...disassembly.matchAll(/^([0-9a-f]+) <([^>]+)>:$/gm)];
  return headers.map((header, index) => ({
    name: header[2],
    body: disassembly.slice(
      header.index,
      index + 1 < headers.length ? headers[index + 1].index : disassembly.length,
    ),
  }));
}

function inspect(path) {
  const bytes = readFileSync(path);
  if (!WebAssembly.validate(bytes)) throw new Error(`${path}: invalid Wasm`);
  const module = new WebAssembly.Module(bytes);
  return {
    path,
    sha256: sha256(bytes),
    bytes: bytes.length,
    codeSectionBytes: codeSectionBytes(bytes),
    imports: WebAssembly.Module.imports(module),
    exports: WebAssembly.Module.exports(module),
    bodies: functionBodies(command("llvm-objdump", ["-d", path])),
  };
}

function pendingTopology(artifact) {
  const setters = artifact.bodies.filter(({ name }) => name === "jit_set_yield_on_pending");
  if (setters.length !== 1) {
    throw new Error(`${artifact.path}: expected one pending setter, found ${setters.length}`);
  }
  const stores = [...setters[0].body.matchAll(/\bi32\.store8\s+(\d+)\b/g)];
  if (stores.length !== 1) {
    throw new Error(`${artifact.path}: pending setter has ${stores.length} byte stores`);
  }
  const flagOffset = Number(stores[0][1]);
  const drivers = artifact.bodies.filter(({ name }) =>
    name.startsWith("_RINv") && name.includes("14run_system_jit") && name.endsWith("EB2_"));
  return {
    flagOffset,
    drivers: drivers.map(({ name, body }) => ({
      name,
      pendingFlagLoads: [...body.matchAll(
        new RegExp(`\\bi32\\.load8_u\\s+${flagOffset}\\b`, "g"),
      )].length,
    })),
  };
}

function archiveFile(archive, path) {
  return command("tar", ["-xOzf", archive, path]);
}

function removeExact(text, fragment, expectedCount, label) {
  const count = text.split(fragment).length - 1;
  if (count !== expectedCount) {
    throw new Error(`${label}: expected ${expectedCount} exact occurrences, found ${count}`);
  }
  return text.split(fragment).join("");
}

const control = inspect(controlPath);
const candidate = inspect(candidatePath);
const archivedR064 = inspect(r064Path);
const candidateTopology = pendingTopology(candidate);
const r064Topology = pendingTopology(archivedR064);

const pendingDeclaration = `/// R064's host-lifecycle boundary. When an asynchronous region is in flight,
/// return from the current bounded system call after the policy-issue
/// boundary so an event-driven host can publish it before more guest work
/// runs in the residual interpreter. This changes no guest quantum, policy,
/// generated bytes, or synchronous embedding contract.
static mut YIELD_ON_PENDING: bool = false;

#[no_mangle]
pub extern "C" fn jit_set_yield_on_pending(on: u32) {
    unsafe { YIELD_ON_PENDING = on != 0 };
}

`;
const pendingCheck = (indent) =>
  `${indent}if unsafe { YIELD_ON_PENDING && !PENDING_SB.is_empty() } {\n` +
  `${indent}    break;\n` +
  `${indent}}\n`;
const currentCore = readFileSync(join(root, "crates/rv64-core/src/cpu.rs"));
const currentWasmText = readFileSync(join(root, "crates/rv64-wasm/src/lib.rs"), "utf8");
let strippedWasm = removeExact(
  currentWasmText,
  pendingDeclaration,
  1,
  "pending declaration/setter",
);
strippedWasm = removeExact(
  strippedWasm,
  pendingCheck("        "),
  1,
  "outer post-issue pending check",
);
strippedWasm = removeExact(
  strippedWasm,
  pendingCheck("            "),
  1,
  "inner post-issue pending check",
);
const archivedR105Wasm = archiveFile(
  r105SourceArchive,
  "crates/rv64-wasm/src/lib.rs",
);
const archivedR105Core = archiveFile(
  r105SourceArchive,
  "crates/rv64-core/src/cpu.rs",
);

const compact = (artifact) => ({
  path: artifact.path,
  sha256: artifact.sha256,
  bytes: artifact.bytes,
  codeSectionBytes: artifact.codeSectionBytes,
  imports: artifact.imports,
  exports: artifact.exports,
});
const problems = [];
const check = (condition, message) => {
  if (!condition) problems.push(message);
};

check(control.sha256 === EXPECTED.control, "control is not exact d9f baseline");
check(candidate.sha256 === EXPECTED.candidate, "candidate artifact changed");
check(archivedR064.sha256 === EXPECTED.r064, "R064 reference artifact changed");
check(sha256(currentCore) === EXPECTED.r105Core, "current scalar core is not exact R105");
check(sha256(archivedR105Core) === EXPECTED.r105Core, "R105 archive core changed");
check(sha256(archivedR105Wasm) === EXPECTED.r105WasmSource, "R105 archive Wasm source changed");
check(sha256(strippedWasm) === EXPECTED.r105WasmSource,
  "subtracting the exact publication mechanism does not recover R105");
check(JSON.stringify(control.imports) === JSON.stringify(candidate.imports),
  "candidate imports changed");

const controlExports = new Map(control.exports.map((entry) => [entry.name, entry.kind]));
const candidateExports = new Map(candidate.exports.map((entry) => [entry.name, entry.kind]));
const addedExports = [...candidateExports]
  .filter(([name]) => !controlExports.has(name))
  .sort(([a], [b]) => a.localeCompare(b));
const removedExports = [...controlExports]
  .filter(([name]) => !candidateExports.has(name))
  .sort(([a], [b]) => a.localeCompare(b));
const changedExports = [...controlExports]
  .filter(([name, kind]) => candidateExports.has(name) && candidateExports.get(name) !== kind);
check(JSON.stringify(addedExports) === JSON.stringify([
  ["jit_set_integrated_scalar_t0", "function"],
  ["jit_set_yield_on_pending", "function"],
]), `unexpected added exports: ${JSON.stringify(addedExports)}`);
check(removedExports.length === 0, `removed exports: ${JSON.stringify(removedExports)}`);
check(changedExports.length === 0, `changed exports: ${JSON.stringify(changedExports)}`);

for (const [label, topology] of [
  ["candidate", candidateTopology],
  ["R064", r064Topology],
]) {
  check(topology.drivers.length === 2, `${label}: expected two concrete system drivers`);
  for (const driver of topology.drivers) {
    check(driver.pendingFlagLoads === 2,
      `${label}: ${driver.name} has ${driver.pendingFlagLoads}, not two pending checks`);
  }
}

const report = {
  schema: 1,
  experiment: "R106",
  mechanism: "exact-r105-scalar-plus-r064-publication-boundary",
  artifacts: {
    control: compact(control),
    candidate: compact(candidate),
    archivedR064: compact(archivedR064),
  },
  sourceProof: {
    currentCoreSha256: sha256(currentCore),
    archivedR105CoreSha256: sha256(archivedR105Core),
    archivedR105WasmSha256: sha256(archivedR105Wasm),
    publicationSubtractedWasmSha256: sha256(strippedWasm),
  },
  abi: { addedExports, removedExports, changedExports },
  topology: { candidate: candidateTopology, archivedR064: r064Topology },
  pass: problems.length === 0,
  problems,
};
writeFileSync(outputPath, `${JSON.stringify(report, null, 2)}\n`, { flag: "wx" });
if (problems.length) process.exitCode = 1;
